// Production server :3017, isolated headless Chrome CDP :9231.
// Screenshots are saved to .tmp/shopping-ui. No backend orders are submitted.
import assert from 'node:assert/strict'
import { browser } from './ui-browser-helpers.mjs'

const { cdp, evaluate, until, visit, click, fill, select, viewport, screenshot, layout, errors, close } = await browser()
try {
  await viewport(1440)
  await visit('/?browse=1')
  await evaluate("localStorage.removeItem('parallel:shopping:v1')")
  await visit('/?browse=1')
  await until("document.querySelectorAll('.department-card').length === 6")
  await layout()
  await screenshot('homepage-desktop')
  assert.equal(await evaluate("document.querySelectorAll('.hero-showcase__item').length"), 3)
  await fill('#site-search', 'paperback')
  await select('#search-department', 'books')
  await click('.header-search button')
  await until("location.pathname === '/category/books' && document.querySelectorAll('.product-card').length === 6")
  await select('.catalogue-field:nth-of-type(2) select', 'Jane Austen')
  await until("document.querySelectorAll('.product-card').length === 1")
  await select('.sort-control select', 'price-high')
  await until("location.search.includes('sort=price-high')")
  await click('[aria-label="Remove Brand: Jane Austen"]')
  await until("document.querySelectorAll('.product-card').length === 6")
  await fill('[name=min]', '10')
  await fill('[name=max]', '15')
  await click('.price-filter button')
  await until("location.search.includes('min=10') && location.search.includes('max=15')")
  await layout()
  await screenshot('category-desktop')
  await fill('#site-search', 'zzzz-no-such-product')
  await click('.header-search button')
  await until("!!document.querySelector('.empty-state')")
  await click('.empty-state button')
  await until("document.querySelectorAll('.product-card').length === 6")
  console.log('PASS department search, brand, sorting, price, empty results and reset')

  await visit('/product/carbon-steel-wok')
  await layout()
  await screenshot('product-desktop')
  await click('.product-gallery__main')
  await until("document.querySelector('dialog').open")
  await screenshot('gallery-enlarged')
  await cdp('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
  await cdp('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
  await until("!document.querySelector('dialog').open")
  assert.equal(await evaluate('document.activeElement.className'), 'product-gallery__main')
  await click('.purchase-quantity button:last-child')
  await click('.purchase-panel .shop-primary')
  await until("document.querySelector('.cart-count').textContent === '2'")
  await click('.purchase-panel > button:last-of-type')
  await until("document.querySelector('.purchase-panel > button:last-of-type').getAttribute('aria-pressed') === 'true'")
  // Compare through the existing workstream, then preserve the selection through shopping.
  await click('.purchase-panel button[title], .purchase-panel .button--outline')
  const comparisonBefore = await evaluate("localStorage.getItem('parallel:comparison:v1')")
  await visit('/cart')
  await until("document.querySelectorAll('.cart-item').length === 1")
  const total = await evaluate("Number(document.querySelector('.cart-item__total').textContent.replace(/[^0-9.]/g, ''))")
  const each = await evaluate("Number(document.querySelector('.cart-item__body > p:last-of-type').textContent.replace(/[^0-9.]/g, ''))")
  assert.equal(Math.round(total * 100), Math.round(each * 100) * 2)
  await click('.quantity-control button:last-child')
  await until("document.querySelector('.cart-count').textContent === '3'")
  await layout()
  await screenshot('cart-desktop')
  await visit('/cart')
  assert.equal(await evaluate("document.querySelector('.quantity-control output').textContent"), '3')
  await click('.cart-item__actions .text-button')
  await until("!!document.querySelector('.shopping-empty')")
  await visit('/wishlist')
  assert.equal(await evaluate("document.querySelectorAll('.product-card').length"), 1)
  await click('.product-card .shop-primary')
  await until("document.querySelector('.cart-count').textContent === '1'")
  await visit('/category/fashion')
  await click('.product-card .shop-primary')
  await until("document.querySelector('.cart-count').textContent === '2'")
  await visit('/cart')
  await until("document.querySelectorAll('.cart-item').length === 2")
  await screenshot('cart-multiple-desktop')
  assert.equal(await evaluate("localStorage.getItem('parallel:comparison:v1')"), comparisonBefore)
  console.log('PASS image enlargement and Escape focus restore, cart quantity/totals/persistence, wishlist, save for later, cross-category cart, comparison preservation')

  await click('.order-summary .shop-primary')
  await until("location.pathname === '/checkout'")
  await click('.checkout-form button[type=submit]')
  await until("document.querySelectorAll('[aria-invalid=true]').length === 7")
  assert.equal(await evaluate('document.activeElement.id'), 'delivery-name')
  for (const [name, text] of Object.entries({name:'Preview Shopper',email:'preview-shopper@example.com',address:'123 Example Lane',city:'Example City',region:'Example Region',postalCode:'12345'})) await fill(`#delivery-${name}`, text)
  await select('#delivery-country', 'United States')
  await screenshot('checkout-desktop')
  await click('.checkout-form button[type=submit]')
  await until("location.pathname === '/checkout/review'")
  assert.ok(await evaluate("document.querySelector('.checkout-review').textContent.includes('123 Example Lane')"))
  assert.equal(await evaluate("document.querySelector('.order-summary button').disabled"), true)
  await screenshot('checkout-review-desktop')
  assert.ok(!(await evaluate('JSON.stringify({...localStorage})')).includes('preview-shopper'))
  await click('.checkout-review a[href="/order-confirmation?preview=1"]')
  await until("location.pathname === '/order-confirmation'")
  assert.ok(await evaluate("document.querySelector('.confirmation-intro').textContent.includes('no order placed')"))
  await screenshot('confirmation-preview-desktop')
  await visit('/checkout/review')
  assert.ok(await evaluate("document.querySelector('.checkout-review').textContent.includes('not saved after a refresh')"))
  await visit('/orders')
  assert.ok(await evaluate("document.querySelector('.shopping-empty').textContent.includes('No orders have been placed')"))
  console.log('PASS checkout validation, memory-only delivery details, review, disabled unconnected payment, honest confirmation and orders states')

  for (const width of [320, 375, 768, 1024, 1440]) {
    await viewport(width, width < 540 ? 812 : 1000)
    for (const path of ['/?browse=1', '/category/books', '/product/carbon-steel-wok', '/cart', '/wishlist', '/checkout']) {
      await visit(path)
      await layout()
      if ([375, 768].includes(width)) await screenshot(`${path.split('/')[1].split('?')[0] || 'home'}-${width}`)
    }
    console.log(`PASS responsive layouts at ${width}px`)
  }
  await viewport(375, 812)
  await visit('/category/books')
  await click('.catalogue-filter-toggle')
  await until("document.querySelector('.catalogue-filter-toggle').getAttribute('aria-expanded') === 'true'")
  await select('.catalogue-field:nth-of-type(2) select', 'Jane Austen')
  await until("document.querySelectorAll('.product-card').length === 1")
  await layout()
  await click('.menu-toggle')
  await until("!!document.querySelector('.category-nav--open')")
  await click('.category-nav a[href^="/category/fashion"]')
  await until("location.pathname === '/category/fashion' && !document.querySelector('.category-nav--open')")
  await visit('/cart')
  while (await evaluate("!!document.querySelector('.cart-item')")) await click('.cart-item button[aria-label^="Remove "]')
  await until("!!document.querySelector('.shopping-empty') && document.querySelector('.cart-count').textContent === '0'")
  await screenshot('cart-empty-mobile')
  assert.deepEqual(errors.map((error) => error.split('\n')[0]), [], 'Browser errors')
  console.log('PASS mobile filters/navigation, cart removal and empty state, no browser runtime errors')
} finally { close() }
